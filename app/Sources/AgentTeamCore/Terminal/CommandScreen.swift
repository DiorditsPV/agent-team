import Foundation

/// Экран встроенной команды Claude Code (`/mcp`, `/config`, `/status`, `/cost`, `/model`, `/help`, `/resume`, `/memory`…):
/// панель с верхней рамкой «▔▔▔▔» во всю ширину (в рамку бывает врезано уведомление справа), идёт до низа экрана, строки
/// ввода под ней нет. Подсказка внизу бывает разной («Esc to cancel», «Esc to close», «Esc to clear»), а у `/mcp` и `/cost`
/// её нет совсем — поэтому экран узнаётся по рамке, а не по подсказке. В транскрипт такие экраны не пишут: приложение
/// показывает панель как есть и шлёт в неё клавиши.
public enum CommandScreen {
    /// Индекс верхней рамки открытого экрана команды в `plain` (строки экрана как есть, без обрезки отступа); `nil` —
    /// экрана нет.
    ///
    /// - Верх панели — последняя строка, которая начинается с «▔▔▔▔» в нулевом столбце: так Claude Code рисует рамку
    ///   экрана. Та же рамка с отступом — цитата в выводе инструмента или в ответе (кто-то вывел фикстуру экрана), не
    ///   экран.
    /// - Ниже рамки нет рамок «────»: под экраном команды нет ни строки ввода (экран закрыт, рамка осталась в прокрутке),
    ///   ни диалога права или формы. Рамки полей поиска внутри панели («╭───╮») такими рамками не считаются.
    public static func top(_ plain: [String]) -> Int? {
        guard let top = plain.indices.last(where: { plain[$0].hasPrefix("▔▔▔▔") }),
              plain[(top + 1)...].contains(where: { !$0.trimmingCharacters(in: .whitespaces).isEmpty }),
              !plain[(top + 1)...].contains(where: { ScreenMarks.isRule($0) }) else { return nil }
        return top
    }

    /// Открыт ли экран команды.
    public static func isOpen(_ plain: [String]) -> Bool { top(plain) != nil }
}
